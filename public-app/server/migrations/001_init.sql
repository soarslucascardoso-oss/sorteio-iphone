-- Esquema inicial do sorteio (PostgreSQL)

CREATE TABLE settings (
  id                   smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  title                text NOT NULL DEFAULT 'Sorteio de um iPhone 18 Pro Max',
  description          text NOT NULL DEFAULT 'Participe gratuitamente do sorteio de um iPhone 18 Pro Max. Basta informar seu nome completo e e-mail.',
  prize_name           text NOT NULL DEFAULT 'iPhone 18 Pro Max',
  start_at             timestamptz,
  end_at               timestamptz,
  result_at            timestamptz,
  registrations_closed boolean NOT NULL DEFAULT false,
  result_published     boolean NOT NULL DEFAULT false,
  rules_text           text NOT NULL DEFAULT '',
  organizer_name       text NOT NULL DEFAULT '',
  contact_email        text NOT NULL DEFAULT '',
  authorization_number text NOT NULL DEFAULT '',
  updated_at           timestamptz NOT NULL DEFAULT now()
);

