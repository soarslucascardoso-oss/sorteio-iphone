CREATE TABLE entries (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             text NOT NULL,
  email            text NOT NULL,
  email_normalized text NOT NULL,
  status           text NOT NULL DEFAULT 'valid' CHECK (status IN ('valid', 'invalid')),
  consent_at       timestamptz NOT NULL DEFAULT now(),
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX entries_email_unique ON entries (email_normalized);
CREATE INDEX entries_created_at_idx ON entries (created_at);

CREATE TABLE draws (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_id         integer NOT NULL REFERENCES entries (id),
  drawn_at         timestamptz NOT NULL DEFAULT now(),
  eligible_count   integer NOT NULL,
  picked_index     integer NOT NULL,
  actor            text NOT NULL DEFAULT '',
  reason           text NOT NULL DEFAULT '',
  annulled_at      timestamptz,
  annulled_reason  text,
  annulled_by      text
);
-- Garante, no próprio banco, que existe no máximo UM sorteio ativo (não anulado).
CREATE UNIQUE INDEX draws_one_active ON draws ((1)) WHERE annulled_at IS NULL;

CREATE TABLE audit_log (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at      timestamptz NOT NULL DEFAULT now(),
  actor   text NOT NULL DEFAULT '',
  action  text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX audit_log_at_idx ON audit_log (at DESC);
